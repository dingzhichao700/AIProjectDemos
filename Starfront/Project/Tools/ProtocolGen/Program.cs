using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Xml;

/// <summary>
/// 编译前根据服务端导出的协议 xml 生成 C# 收发类。
/// 标量字段自动生成；array / map / 多态 Bean 列表跳过（需手写）。
/// </summary>
internal static class Program {

    static int Main(string[] args) {
        string xmlDir = args.Length > 0 ? args[0] : Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "..", "xml");
        string outDir = args.Length > 1 ? args[1] : Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "..", "..", "..", "Assets", "Scripts", "csharp", "login", "network", "protocol");
        xmlDir = Path.GetFullPath(xmlDir);
        outDir = Path.GetFullPath(outDir);
        if (!Directory.Exists(xmlDir)) {
            Console.Error.WriteLine("xml 目录不存在: " + xmlDir);
            return 1;
        }
        Directory.CreateDirectory(outDir);
        int count = 0;
        foreach (string file in Directory.GetFiles(xmlDir, "*.xml")) {
            count += GenerateFile(file, outDir);
        }
        Console.WriteLine("protocol-gen-ok " + count);
        return 0;
    }

    static int GenerateFile(string xmlPath, string outDir) {
        XmlDocument document = new XmlDocument();
        document.Load(xmlPath);
        XmlNodeList beans = document.SelectNodes("//bean");
        if (beans == null) {
            return 0;
        }
        int count = 0;
        foreach (XmlNode bean in beans) {
            string name = Attr(bean, "name");
            string id = Attr(bean, "id");
            if (string.IsNullOrEmpty(name) || string.IsNullOrEmpty(id)) {
                continue;
            }
            List<FieldDef> fields = new List<FieldDef>();
            bool skip = false;
            foreach (XmlNode child in bean.ChildNodes) {
                if (child.NodeType != XmlNodeType.Element) {
                    continue;
                }
                if (child.Name != "p" && child.Name != "cp") {
                    continue;
                }
                string fieldName = Attr(child, "name");
                string type = Attr(child, "type");
                if (string.IsNullOrEmpty(fieldName) || string.IsNullOrEmpty(type)) {
                    continue;
                }
                if (!IsScalar(type)) {
                    skip = true;
                    break;
                }
                fields.Add(new FieldDef(fieldName, type));
            }
            if (skip) {
                continue;
            }
            string code = BuildClass(name, id, fields);
            string path = Path.Combine(outDir, name + ".cs");
            File.WriteAllText(path, code, new UTF8Encoding(false));
            count++;
        }
        return count;
    }

    static bool IsScalar(string type) {
        return type == "string" || type == "int" || type == "long" || type == "short"
            || type == "byte" || type == "boolean" || type == "bool";
    }

    static string BuildClass(string name, string id, List<FieldDef> fields) {
        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// 由 Tools/ProtocolGen 根据协议 xml 生成，不要手改。");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("public sealed class " + name + " {");
        sb.AppendLine();
        sb.AppendLine("    public const short ProtocolId = " + id + ";");
        sb.AppendLine();
        foreach (FieldDef field in fields) {
            sb.AppendLine("    public " + CsType(field.Type) + " " + field.Name + ";");
        }
        sb.AppendLine();
        sb.AppendLine("    public byte[] Encode() {");
        sb.AppendLine("        NetWriter writer = new NetWriter();");
        foreach (FieldDef field in fields) {
            sb.AppendLine("        " + EncodeLine(field) + ";");
        }
        sb.AppendLine("        return writer.ToArray();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static " + name + " Decode(byte[] body) {");
        sb.AppendLine("        NetReader reader = new NetReader(body);");
        sb.AppendLine("        " + name + " packet = new " + name + "();");
        foreach (FieldDef field in fields) {
            sb.AppendLine("        packet." + field.Name + " = " + DecodeExpr(field) + ";");
        }
        sb.AppendLine("        return packet;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("}");
        return sb.ToString();
    }

    static string CsType(string type) {
        switch (type) {
            case "string":
                return "string";
            case "int":
                return "int";
            case "long":
                return "long";
            case "short":
                return "short";
            case "byte":
                return "byte";
            case "boolean":
            case "bool":
                return "bool";
            default:
                throw new InvalidOperationException("暂只支持标量字段: " + type);
        }
    }

    static string EncodeLine(FieldDef field) {
        switch (field.Type) {
            case "string":
                return "writer.WriteString(" + field.Name + ")";
            case "int":
                return "writer.WriteInt(" + field.Name + ")";
            case "long":
                return "writer.WriteLong(" + field.Name + ")";
            case "short":
                return "writer.WriteShort(" + field.Name + ")";
            case "boolean":
            case "bool":
                return "writer.WriteBool(" + field.Name + ")";
            case "byte":
                return "writer.WriteBytes(new byte[] { " + field.Name + " })";
            default:
                throw new InvalidOperationException("暂只支持标量字段: " + field.Type);
        }
    }

    static string DecodeExpr(FieldDef field) {
        switch (field.Type) {
            case "string":
                return "reader.ReadString()";
            case "int":
                return "reader.ReadInt()";
            case "long":
                return "reader.ReadLong()";
            case "short":
                return "reader.ReadShort()";
            case "boolean":
            case "bool":
                return "reader.ReadBool()";
            case "byte":
                return "reader.ReadByte()";
            default:
                throw new InvalidOperationException("暂只支持标量字段: " + field.Type);
        }
    }

    static string Attr(XmlNode node, string name) {
        if (node.Attributes == null) {
            return null;
        }
        XmlAttribute attribute = node.Attributes[name];
        return attribute == null ? null : attribute.Value;
    }

    sealed class FieldDef {
        public readonly string Name;
        public readonly string Type;

        public FieldDef(string name, string type) {
            Name = name;
            Type = type;
        }
    }

}
